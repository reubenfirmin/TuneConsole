"""A worker-prepared video pool, ranked by the same candidates as Mix tapes.

Videos retain their taste connection separately from their playable upload. The
first resolver uses recordings; artist-connected long-form videos can share the
same pool without pretending that a concert or set is a single recording.
"""
from collections import Counter
import hashlib
import json
import math
import re

from yt_playlist.core.activity import check_cancellable_work, WorkBudgetExceeded, WorkClosing
from yt_playlist.rec import fresh_pool, home_prepared, tv_visual
from yt_playlist.rec.eligibility import home_exclusions
from yt_playlist.util.duration import parse_duration
from yt_playlist.util.matching import identity_key, normalize, search_squash, track_artist
from yt_playlist.util.thumbnails import best_thumb

SURFACE = 'tv_pool'
SETTING = 'tv_max_minutes'
GROUPS = ('liked', 'your_artists', 'discovery')
MAX_POOL = 60
MAX_SEEDS = 3
SEARCHES = ('music video', 'live', 'session', 'visualizer')
SCHEMA = 3
QUEUE_SIZE = 12
MAX_AGE = 86400
SEARCH_RETRY_S = 300
_VIDEO = re.compile(r'^[A-Za-z0-9_-]{11}$')
_VISUAL = re.compile(r'\b(visuali[sz]er|music video|official video|live|session|performance|concert)\b', re.I)
_STILL = re.compile(r'\b(official audio|audio only|lyric(?:s| video)?|full album|static image|'
                    r'still image|album stream|audio stream|art track)\b', re.I)
_STILL_DESCRIPTION = re.compile(r'\b(provided to youtube by|auto-generated by youtube|'
                               r'static image|still image|audio only|art track)\b', re.I)


def max_minutes(store):
    value = store.settings.get_setting(SETTING)
    if value == 'unlimited':
        return None
    try:
        return max(1, int(value or 15))
    except (ValueError, TypeError):
        return 15


def _interleave(lanes, limit, offset=0):
    lanes = [lane[offset % len(lane):] + lane[:offset % len(lane)] for lane in lanes if lane]
    seen, tracks = set(), []
    for index in range(max(map(len, lanes), default=0)):
        for lane in lanes:
            if index < len(lane) and lane[index]['key'] not in seen:
                track = lane[index]
                seen.add(track['key'])
                tracks.append(track)
                if len(tracks) == limit:
                    return tracks
    return tracks


def seed_tracks(store, now, offset=0):
    """Worker-only: reuse prepared ranks, without fitting or logging mix exposure."""
    payload = home_prepared.load(store, now)
    if not payload or not any(m.get('protos') for m in payload['menus']):
        return []
    library = store.rec_query.library_songs()
    owned = {t['key'] for t in library}
    liked = {t['key'] for t in library if t['liked']} | set(store.rec_model.recent_liked_keys())
    artists = {search_squash(t['artist']) for t in library}
    prepared = [p['tracks'] for m in payload['menus'] for p in m['protos']]
    bundles = store.rec_proposals.get_proposals('mode_bundles') or {}
    prepared.extend(bucket.get(lane, []) for mid, bucket in bundles.items()
                    if not mid.startswith('_') for lane in ('wheelhouse', 'comfort', 'explore'))
    ranked = _interleave(prepared, 1200)
    # Likes absent from a shallow prepared menu still deserve a chance, after
    # model-ranked likes. Never substitute all owned songs for explicit likes.
    ranked.extend(t for t in library if t['key'] in liked)
    lanes = {group: [] for group in GROUPS}
    lanes['liked'] = [{**t, 'group': 'liked'} for t in ranked if t['key'] in liked]
    for track in fresh_pool.pick(store, now, size=120, minimum=1):
        if track['key'] in owned:
            continue
        group = 'your_artists' if search_squash(track['artist']) in artists else 'discovery'
        lanes[group].append({**track, 'group': group})
    tracks = _interleave([lanes[g] for g in GROUPS], MAX_POOL, offset=offset)
    blocked = home_exclusions(store, [t['key'] for t in tracks], now)
    muted = store.rec_model.muted_artists()
    return [t for t in tracks if t['key'] not in blocked and t['artist'] not in muted]


def eligible(store, items, maximum, now):
    """Current suppression is a hard constraint, including while a job was searching."""
    if not isinstance(items, list) or len(items) > MAX_POOL:
        return []
    items = [t for t in items if isinstance(t, dict)
             and all(isinstance(t.get(k), str) for k in
                     ('video_id', 'title', 'artist', 'kind', 'source_key', 'source_artist'))
             and _VIDEO.fullmatch(t['video_id']) and type(t.get('duration')) is int]
    upload_keys = {t['video_id']: (store.tracks.identity_key_for_video(t['video_id'])
                                  or identity_key(t['title'], t['artist'])) for t in items}
    blocked = home_exclusions(store, [t['source_key'] for t in items], now)
    # Video uploads are deliberately saved in Generated playlists. That origin
    # must not exclude them from subsequent TV draws; feedback still applies.
    blocked |= store.rec_model.suppressed_keys('for_you', now, keys=list(upload_keys.values()))
    muted = store.rec_model.muted_artists()
    static = tv_visual.static_ids(store)
    return [t for t in items if t['source_key'] not in blocked
            and t['video_id'] not in static
            and upload_keys[t['video_id']] not in blocked
            and t['artist'] not in muted and t['source_artist'] not in muted
            and t.get('group') in GROUPS and t['duration'] > 0
            and (maximum is None or t['duration'] <= maximum * 60)]


def cached(store):
    payload = store.rec_proposals.get_proposals(SURFACE) or {}
    if (not isinstance(payload, dict) or payload.get('schema') != SCHEMA
            or type(payload.get('at')) not in (int, float) or not math.isfinite(payload['at'])
            or not isinstance(payload.get('key'), str)
            or not isinstance(payload.get('attempted'), list) or len(payload['attempted']) > MAX_POOL
            or any(not isinstance(key, str) for key in payload['attempted'])
            or not isinstance(payload.get('items'), list) or len(payload['items']) > MAX_POOL):
        return None
    return payload


def draw_number(store):
    try:
        return max(0, int(store.settings.get_setting('tv_draw') or 0))
    except (ValueError, TypeError):
        return 0


def _video_history(store, setting, limit):
    try:
        values = json.loads(store.settings.get_setting(setting) or '[]')
        return [v for v in values[-limit:] if isinstance(v, str) and _VIDEO.fullmatch(v)] if isinstance(values, list) else []
    except (TypeError, ValueError):
        return []


def record_draw(store, items):
    """Remember confirmed sessions, so a fresh draw favors other prepared videos."""
    videos = list(dict.fromkeys(item['video_id'] for item in items))
    history = [v for v in _video_history(store, 'tv_recent_videos', MAX_POOL) if v not in videos]
    store.settings.set_setting('tv_recent_videos', json.dumps((history + videos)[-MAX_POOL:]))
    store.settings.set_setting('tv_last_videos', json.dumps(videos))
    store.settings.set_setting('tv_draw', str(draw_number(store) + 1))


def queue(store, now, *, exclude=(), recent=(), current=None, limit=QUEUE_SIZE):
    """A bounded draw from the pool; length changes never require another search."""
    items = eligible(store, (cached(store) or {}).get('items', []), max_minutes(store), now)
    excluded = set(exclude)
    if current:
        excluded.add(current)
    items = [item for item in items if item['video_id'] not in excluded]
    draw = draw_number(store)
    history = (_video_history(store, 'tv_recent_videos', MAX_POOL) + list(recent))[-MAX_POOL:]
    recent = {video: index for index, video in enumerate(history)}
    last = _video_history(store, 'tv_last_videos', QUEUE_SIZE)
    def freshness(item):
        video = item['video_id']
        if video in last:
            return 2, 0
        return (1, recent[video]) if video in recent else (0, 0)
    if draw:
        items.sort(key=lambda item: hashlib.sha256(f"{draw}:{item['video_id']}".encode()).digest())
    items.sort(key=freshness)
    lanes = [[{**item, 'key': item['video_id']} for item in items if item['group'] == group]
             for group in GROUPS]
    drawn = sorted(_interleave(lanes, MAX_POOL), key=freshness)
    artists, picked = Counter(), []
    for item in drawn:
        if artists[item['source_artist']] < 3:
            artists[item['source_artist']] += 1
            picked.append(item)
        if len(picked) == limit:
            break
    if len(picked) > 1 and last and picked[0]['video_id'] == last[0]:
        picked[0], picked[1] = picked[1], picked[0]
    return picked


def prepare(store, client, now):
    """One small network slice. Publish progressively and keep the last good pool."""
    # Search outside the serving connection. If inputs change during network
    # work, the same publication guard used by Mix tapes rejects this slice.
    try:
        with store.read_snapshot() as snapshot:
            more = _prepare(store, snapshot, client, now)
    except (WorkBudgetExceeded, WorkClosing):
        raise
    except Exception:
        store.rec_proposals.put_proposals('tv_preparation', {'failed': True, 'at': now}, now)
        raise
    store.rec_proposals.put_proposals('tv_preparation', {'failed': False, 'at': now}, now)
    return more


def _prepare(store, snapshot, client, now):
    reader = snapshot.store
    previous = cached(reader) or {}
    offset = previous.get('offset', 0)
    seeds = seed_tracks(reader, now, offset)
    if not seeds:
        # A transient empty Home preparation must not erase playable videos.
        # Retain only sources still present and allowed by current feedback.
        items = eligible(reader, previous.get('items', []), None, now)
        keys = [t['source_key'] for t in items]
        available = (set(reader.rec_query.tracks_by_keys(keys))
                     | set(reader.discovery.discovered_tracks_by_keys(keys, available_only=True)))
        items = [t for t in items if t['source_key'] in available]
        payload = {'schema': SCHEMA, 'key': 'no-sources', 'at': now, 'items': items,
                   'attempted': [], 'state': 'no_sources', 'retry_at': now + SEARCH_RETRY_S}
        snapshot.publish(lambda: store.rec_proposals.publish_prepared_home(json.dumps(payload), now, surface=SURFACE))
        return False
    current_keys = {t['key'] for t in seeds}
    reusable = 0 <= now - previous.get('at', -MAX_AGE) < MAX_AGE
    # Home ranks can change between network slices. Continue by recording key
    # instead of restarting at seed one whenever the menu changes order or gains
    # a new candidate, and retain usable prepared videos through that refresh.
    attempted = set(previous.get('attempted', [])) & current_keys if reusable else set()
    previous_items = eligible(reader, previous.get('items', []), None, now) if reusable else []
    source_keys = [t['source_key'] for t in previous_items]
    retained = (current_keys | set(reader.rec_query.tracks_by_keys(source_keys))
                | set(reader.discovery.discovered_tracks_by_keys(source_keys, available_only=True)))
    items = [t for t in previous_items if t['source_key'] in retained]
    groups = {t['key']: t['group'] for t in seeds}
    items = [{**t, 'group': groups.get(t['source_key'], t['group'])} for t in items]
    pending = [t for t in seeds if t['key'] not in attempted]
    if not pending:
        if now < previous.get('retry_at', previous.get('at', now) + SEARCH_RETRY_S):
            return False
        # Search farther into the same taste-ranked lanes after a bounded quiet
        # interval. Exhausted/no-result seeds cannot strand TV until tomorrow.
        offset += MAX_POOL // len(GROUPS)
        seeds = seed_tracks(reader, now, offset)
        attempted = set()
        pending = seeds
        if not pending:
            return False
    key = hashlib.sha256(json.dumps(sorted([t['key'], t['group'], t['title'], t['artist']]
                                           for t in seeds)).encode()).hexdigest()[:24]
    batch = pending[:MAX_SEEDS]
    found = resolve(client, batch, None)
    check_cancellable_work()
    seen = {t['video_id'] for t in items}
    items.extend(t for t in found if t['video_id'] not in seen)
    attempted.update(t['key'] for t in batch)
    payload = {'schema': SCHEMA, 'key': key,
        'at': previous['at'] if reusable else now, 'items': items[-MAX_POOL:],
        'attempted': sorted(attempted), 'offset': offset,
        'state': 'searching' if len(pending) > len(batch) else 'exhausted',
        'retry_at': 0 if len(pending) > len(batch) else now + SEARCH_RETRY_S}
    encoded = json.dumps(payload, separators=(',', ':'))
    published = snapshot.publish(lambda: store.rec_proposals.publish_prepared_home(encoded, now, surface=SURFACE))
    return not published or len(pending) > len(batch)


def video_kind(row):
    title = row.get('title') or ''
    if _STILL.search(title) or row.get('videoType') in {'MUSIC_VIDEO_TYPE_ATV', 'ATV'}:
        return None
    match = _VISUAL.search(title)
    if match:
        label = match.group().lower()
        return ('Visualizer' if label in ('visualizer', 'visualiser') else
                'Live session' if label in ('live', 'session', 'performance', 'concert') else 'Music video')
    if row.get('videoType') == 'MUSIC_VIDEO_TYPE_OMV':
        return 'Music video'
    return None


def resolve(client, seeds, maximum):
    items, seen = [], set()
    for seed in seeds[:MAX_SEEDS]:
        check_cancellable_work()
        # Search the requested editions separately. A broad music-video query
        # often ranks an album upload above an actual performance. At most
        # twelve searches and six detailed lookups are admitted per slice.
        rows = {}
        for edition in SEARCHES:
            check_cancellable_work()
            for row in (client.search(f"{seed['artist']} {seed['title']} {edition}", filter='videos') or [])[:8]:
                rows.setdefault(row.get('videoId'), row)
        matches = []
        for row in rows.values():
            vid = row.get('videoId') or ''
            kind = video_kind(row)
            if not _VIDEO.fullmatch(vid) or vid in seen or not kind:
                continue
            artist = track_artist(row)
            wanted = search_squash(seed['artist'])
            credits = search_squash(artist or row.get('title', ''))
            if not wanted or wanted not in credits:
                continue
            # A visual title alone is not evidence of the recommended recording.
            title_words = set(normalize(seed['title']).split())
            if not title_words or not title_words <= set(normalize(row.get('title', '')).split()):
                continue
            quality = {'Live session': 3, 'Music video': 2, 'Visualizer': 1}[kind]
            # Prefer footage over a visualizer even when its search position is
            # lower. An official music-video type gives an additional signal.
            quality += row.get('videoType') == 'MUSIC_VIDEO_TYPE_OMV'
            matches.append((quality, row, kind, artist))
        matches.sort(key=lambda match: -match[0])
        for _quality, row, kind, artist in matches[:2]:
            check_cancellable_work()
            vid = row['videoId']
            song = client.get_song(vid) or {}
            details = song.get('videoDetails') or {}
            playback = song.get('playabilityStatus') or {}
            if (playback.get('status', 'OK') != 'OK' or playback.get('playableInEmbed') is False
                    or details.get('isLive') or row.get('isLive')):
                continue
            video_type = details.get('musicVideoType') or song.get('microformat', {}).get(
                'microformatDataRenderer', {}).get('musicVideoType')
            description = details.get('shortDescription') or ''
            if (video_type in {'MUSIC_VIDEO_TYPE_ATV', 'ATV'}
                    or _STILL.search(details.get('title') or '')
                    or _STILL_DESCRIPTION.search(description)
                    or (details.get('author') or '').casefold().endswith(' - topic')):
                continue
            raw = details.get('lengthSeconds') or row.get('duration_seconds') or parse_duration(row.get('duration'))
            try:
                duration = int(raw)
            except (TypeError, ValueError, OverflowError):
                continue
            if duration <= 0 or (maximum is not None and duration > maximum * 60):
                continue
            seen.add(vid)
            items.append({'video_id': vid, 'title': row['title'], 'artist': artist or seed['artist'],
                          'thumbnail': best_thumb(row.get('thumbnails')), 'duration': duration, 'kind': kind,
                          'source_key': seed['key'], 'source_artist': seed['artist'],
                          'group': seed.get('group', 'liked'), 'connection': 'track'})
            break
    return items


