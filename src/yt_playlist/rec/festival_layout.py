def trails(nodes):
    """Light shared walking sections once, preferring open over preparing."""
    stops = {node['id']: node for node in nodes}
    result = []
    for identity, destinations, path in TRAILS:
        users = [stops[destination] for destination in destinations]
        if any(node['connected'] for node in users):
            state = 'connected'
        elif any(node['ready'] and node['state'] == 'explored' for node in users):
            state = 'explored'
        elif any(node['ready'] for node in users):
            state = 'ready'
        elif any(node['state'] == 'preparing' and not node['optional'] for node in users):
            state = 'preparing'
        else:
            state = 'untouched'
        result.append({'id': identity, 'destinations': destinations, 'path': path,
                       'state': state, 'parent': stops.get(identity, {}).get('parent', '')})
    return result
