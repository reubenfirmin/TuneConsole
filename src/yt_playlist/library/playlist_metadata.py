"""Playlist naming and provenance shared by readers and writers, with no orchestration imports."""
import hashlib


# The description is account-visible, so another installation can recognize generated playlists.
GENERATED_DESCRIPTION = "Generated by TuneConsole"
PROMOTED_DESCRIPTION = "Promoted into your library from TuneConsole"


def is_generated_description(text):
    return GENERATED_DESCRIPTION.lower() in (text or "").strip().lower()


def content_hash(track_keys):
    return hashlib.sha256("\n".join(sorted(track_keys)).encode("utf-8")).hexdigest()


def versioned_title(store, prefix):
    """Increment the suffix over playlists sharing a generated title's prefix."""
    n = 1 + sum(1 for p in store.playlists.get_playlists() if p.title.startswith(prefix))
    return f"{prefix} #{n}"
