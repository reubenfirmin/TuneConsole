import {coverage, windows, POLICY} from './sampling.js';

const $ = id => document.getElementById(id);
const player = $('player');
const tab = await chrome.tabs.getCurrent();
let source = null, objectURL = null, epoch = 0, capture = null, loading = 0;
let results = [], reference = null;
const send = data => chrome.runtime.sendMessage({target: 'background', ...data}).catch(() => {});

function state() {
  return {source, epoch, position: player.currentTime, duration: player.duration,
    paused: player.paused || player.ended || player.seeking || player.readyState < 3,
    rate: player.playbackRate, permitted: $('permitted').checked,
    permission_note: $('permission-note').value.trim(), model: $('model').checked, at: Date.now()};
}
function update() { send({type: 'state', state: state()}); }
function changed() { epoch++; update(); }
for (const event of ['play', 'pause', 'seeking', 'seeked', 'ended', 'emptied', 'ratechange', 'waiting', 'playing']) {
  player.addEventListener(event, changed);
}
for (const id of ['permitted', 'permission-note', 'title', 'artist', 'album', 'model']) {
  $(id).addEventListener('input', () => {
    send({type: 'stop'});
    results = [];
    $('results').replaceChildren();
    $('export').disabled = true;
    changed();
  });
}
setInterval(update, 200);
window.addEventListener('pagehide', () => send({type: 'stop'}));
$('stop').addEventListener('click', () => send({type: 'stop'}));
async function checkModelAssets() {
  try {
    const response = await fetch('vendor/bundle.json');
    if (!response.ok) throw Error('No local bundle');
    await response.json();
    $('model').disabled = false;
    const runtime = await fetch('vendor/runtime.json').catch(() => null);
    $('model-status').textContent = runtime?.ok
      ? 'Local MusiCNN research model available. Native tag predictions are unvalidated; CPU analysis may take several seconds per window.'
      : 'The original runtime is blocked by Chrome’s extension security policy. Build the optional compatible runtime to try model inference. This probe stops capture on failure.';
  } catch {
    $('model-status').textContent = 'Optional model not installed. Signal measurements are available.';
  }
}

async function load(file, demo = false) {
  const version = ++loading;
  await send({type: 'stop'});
  player.pause();
  source = null;
  results = [];
  reference = null;
  $('results').replaceChildren();
  $('export').disabled = true;
  if (objectURL) URL.revokeObjectURL(objectURL);
  objectURL = null;
  player.removeAttribute('src');
  player.load();
  $('identity').textContent = 'Loading reference…';
  if (!file || file.size > 64 * 1024 * 1024) {
    $('identity').textContent = 'Choose an audio file up to 64 MiB.';
    return;
  }
  const bytes = await file.arrayBuffer();
  const hash = await crypto.subtle.digest('SHA-256', bytes);
  new Uint8Array(bytes).fill(0);
  if (version !== loading) return;
  source = 'sha256:' + Array.from(new Uint8Array(hash), b => b.toString(16).padStart(2, '0')).join('');
  objectURL = URL.createObjectURL(file);
  player.src = objectURL;
  $('title').value = demo ? 'Generated 440 Hz capture check' : file.name;
  $('artist').value = demo ? 'TuneConsole audio lab' : '';
  $('album').value = '';
  $('permission-note').value = demo ? 'Generated by this lab; CC0-1.0. Synthetic capture check only.' : '';
  $('permitted').checked = demo;
  reference = {source, filename: file.name, bytes: file.size, synthetic: demo};
  $('identity').textContent = source;
  $('status').textContent = 'Analysis off. Start playback and use the toolbar icon to enable.';
  changed();
}
$('file').addEventListener('change', () => load($('file').files[0]));
$('demo').addEventListener('click', () => {
  const rate = 16000, seconds = 75, count = rate * seconds;
  const bytes = new ArrayBuffer(44 + 2 * count), v = new DataView(bytes);
  const text = (offset, value) => [...value].forEach((c, i) => v.setUint8(offset + i, c.charCodeAt(0)));
  text(0, 'RIFF'); v.setUint32(4, 36 + count * 2, true); text(8, 'WAVE'); text(12, 'fmt ');
  v.setUint32(16, 16, true); v.setUint16(20, 1, true); v.setUint16(22, 1, true);
  v.setUint32(24, rate, true); v.setUint32(28, rate * 2, true); v.setUint16(32, 2, true);
  v.setUint16(34, 16, true); text(36, 'data'); v.setUint32(40, count * 2, true);
  for (let i = 0; i < count; i++) v.setInt16(44 + i * 2, Math.round(32767 * .1 * Math.sin(2 * Math.PI * 440 * i / rate)), true);
  load(new File([bytes], 'capture-check.wav', {type: 'audio/wav'}), true);
});

chrome.runtime.onMessage.addListener((message, sender, reply) => {
  if (message.target !== 'reference' || message.tabId !== tab.id) return;
  if (message.status === 'capturing') {
    capture = message.session;
    $('status').textContent = 'Analysis on. Playback remains audible.';
    $('stop').disabled = false;
    update();
  } else if (message.status === 'sample' && message.result?.source === source
      && capture && message.result.id?.startsWith(capture + '/')) {
    const result = message.result;
    if (results.some(row => row.id === result.id)) return;
    results.push(result);
    const item = document.createElement('li');
    item.textContent = `${result.start.toFixed(2)}–${result.end.toFixed(2)} s: `
      + `RMS ${result.descriptors.rms.toFixed(5)}, peak ${result.descriptors.peak.toFixed(5)}. `
      + `${result.partial ? 'Partial window. ' : ''}${result.wall_ms.toFixed(2)} ms analysis.`;
    if (result.prediction) item.textContent += ` Model: ${result.prediction.status}; CPU backend ${result.prediction.backend}.`;
    $('results').append(item);
    $('export').disabled = false;
  } else if (['error', 'ended', 'stopped'].includes(message.status)) {
    capture = null;
    $('stop').disabled = true;
    $('status').textContent = message.error || message.reason || 'Analysis off';
  }
  reply({ok: true});
});
$('export').addEventListener('click', () => {
  const payload = {schema: 1, status: 'unlabelled_reference_measurements',
    reference: {...reference, title: $('title').value, artist: $('artist').value, album: $('album').value,
      permission_note: $('permission-note').value},
    human_judgments: null, recommendation_adoption: false,
    sampling: {policy: POLICY, planned_windows: windows(player.duration),
      capture_coverage: coverage(results, player.duration),
      model_coverage: coverage(results.filter(row => row.prediction).map(row => ({
        start: row.start, end: row.start + row.prediction.analysed_seconds})), player.duration),
      coverage_is_reliability: false}, results};
  const url = URL.createObjectURL(new Blob([JSON.stringify(payload, null, 2) + '\n'], {type: 'application/json'}));
  const a = document.createElement('a'); a.href = url; a.download = 'tuneconsole-audio-reference.json'; a.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
});

